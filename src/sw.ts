
import { precacheAndRoute, cleanupOutdatedCaches, createHandlerBoundToURL } from 'workbox-precaching';
import { registerRoute, NavigationRoute } from 'workbox-routing';
import { NetworkFirst, CacheFirst, StaleWhileRevalidate } from 'workbox-strategies';
import { CacheableResponsePlugin } from 'workbox-cacheable-response';
import { ExpirationPlugin } from 'workbox-expiration';
import { clientsClaim } from 'workbox-core';

declare const self: ServiceWorkerGlobalScope & { __WB_MANIFEST: Array<{ url: string; revision: string | null }> };

// Take control immediately
clientsClaim();
self.skipWaiting();

// Precache all static assets generated by Vite
precacheAndRoute(self.__WB_MANIFEST);

// Clean up outdated caches
cleanupOutdatedCaches();

// SPA Navigation Route — serve index.html for all navigation requests
const navigationHandler = createHandlerBoundToURL('/index.html');
const navigationRoute = new NavigationRoute(navigationHandler, {
  denylist: [/^\/_/, /\/[^/?]+\.[^/]+$/],
});
registerRoute(navigationRoute);

// Cache names - versioned to v4 for PWA fix
const DATA_CACHE = 'lytotec-data-v5';
const API_CACHE = 'lytotec-api-v5';
const LARGE_FILES_CACHE = 'lytotec-large-files-v5';
const ASSETS_CACHE = 'lytotec-assets-v5';

// Cache large JavaScript files with specific strategy
registerRoute(
  ({ url, request }) => 
    request.destination === 'script' && 
    url.pathname.includes('/assets/') && 
    url.pathname.endsWith('.js'),
  new CacheFirst({
    cacheName: LARGE_FILES_CACHE,
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 50,
        maxAgeSeconds: 60 * 60 * 24 * 7, // 7 days
        purgeOnQuotaError: true,
      }),
    ],
  })
);

// Cache API calls with Network First strategy - Dynamic Supabase URL
registerRoute(
  ({ url }) => {
    const supabasePattern = /^https:\/\/[a-z]+\.supabase\.co/;
    return supabasePattern.test(url.origin) && url.pathname.startsWith('/rest/v1/');
  },
  new NetworkFirst({
    cacheName: API_CACHE,
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 300,
        maxAgeSeconds: 60 * 60 * 12, // 12 hours
        purgeOnQuotaError: true,
      }),
    ],
  })
);

// Cache authentication requests - Dynamic Supabase URL
registerRoute(
  ({ url }) => {
    const supabasePattern = /^https:\/\/[a-z]+\.supabase\.co/;
    return supabasePattern.test(url.origin) && url.pathname.startsWith('/auth/v1/');
  },
  new NetworkFirst({
    cacheName: 'lytotec-auth-v5',
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 30,
        maxAgeSeconds: 60 * 15, // 15 minutes
      }),
    ],
  })
);

// Cache static assets with Cache First strategy
registerRoute(
  ({ request }) => request.destination === 'image' || 
                   request.destination === 'font' ||
                   request.destination === 'style',
  new CacheFirst({
    cacheName: ASSETS_CACHE,
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 200,
        maxAgeSeconds: 60 * 60 * 24 * 30, // 30 days
      }),
    ],
  })
);

// Cache Google Fonts with Stale While Revalidate
registerRoute(
  ({ url }) => url.origin === 'https://fonts.googleapis.com' || url.origin === 'https://fonts.gstatic.com',
  new StaleWhileRevalidate({
    cacheName: 'lytotec-fonts-v5',
    plugins: [
      new CacheableResponsePlugin({
        statuses: [0, 200],
      }),
      new ExpirationPlugin({
        maxEntries: 30,
        maxAgeSeconds: 60 * 60 * 24 * 365, // 1 year
      }),
    ],
  })
);

// Handle offline data storage
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'CACHE_DATA') {
    event.waitUntil(cacheOfflineData(event.data.key, event.data.data));
  }
  
  if (event.data && event.data.type === 'GET_CACHED_DATA') {
    event.waitUntil(getCachedData(event.data.key).then(data => {
      event.ports[0].postMessage({ data });
    }));
  }
  
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

// Cache offline data
async function cacheOfflineData(key: string, data: any) {
  try {
    const cache = await caches.open(DATA_CACHE);
    const response = new Response(JSON.stringify(data), {
      headers: { 'Content-Type': 'application/json' }
    });
    await cache.put(new Request(`/offline-data/${key}`), response);
    console.log(`💾 Cached data for key: ${key}`);
  } catch (error) {
    console.error('Error caching offline data:', error);
  }
}

// Retrieve cached data
async function getCachedData(key: string) {
  try {
    const cache = await caches.open(DATA_CACHE);
    const response = await cache.match(`/offline-data/${key}`);
    if (response) {
      const data = await response.json();
      console.log(`📖 Retrieved cached data for key: ${key}`);
      return data;
    }
    return null;
  } catch (error) {
    console.error('Error retrieving cached data:', error);
    return null;
  }
}

// Background sync for offline actions
self.addEventListener('sync', (event) => {
  console.log('🔄 Background sync triggered:', event.tag);
  
  if (event.tag === 'sync-offline-data') {
    event.waitUntil(syncOfflineData());
  }
});

// Sync offline data when connection is restored
async function syncOfflineData() {
  try {
    const clients = await self.clients.matchAll();
    if (clients.length > 0) {
      clients[0].postMessage({ type: 'SYNC_OFFLINE_DATA' });
    }
  } catch (error) {
    console.error('Error syncing offline data:', error);
  }
}

// Install event
self.addEventListener('install', () => {
  console.log('🚀 Service Worker installing...');
  // skipWaiting já é chamado no topo do arquivo
});

// Activate event - clean old caches
self.addEventListener('activate', (event) => {
  console.log('✅ Service Worker activated - cleaning old caches');
  const currentCaches = [DATA_CACHE, API_CACHE, LARGE_FILES_CACHE, ASSETS_CACHE, 'lytotec-auth-v5', 'lytotec-fonts-v5'];
  event.waitUntil(
    caches.keys().then(keys =>
      Promise.all(keys
        .filter(key => key.startsWith('lytotec-') && !currentCaches.includes(key))
        .map(key => { console.log('🗑️ Deleting old cache:', key); return caches.delete(key); })
      )
    ).then(() => self.clients.claim())
  );
});

console.log('🏗️ Service Worker loaded and ready');
